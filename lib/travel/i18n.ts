export function isTravelLocale(locale: string): locale is TravelLocale {
  return (travelLocaleCodes as readonly string[]).includes(locale);
}
export function travelText(locale: TravelLocale) {
  return travelLanguageInfo.find((row) => row.code === locale)!;
}
export function travelBase(locale: TravelLocale) {
  return locale === 'fr' ? '/travel' : `/${locale}/travel`;
}
export function travelHref(locale: TravelLocale, slug = '') {
  return travelBase(locale) + (slug ? '/' + slug.replace(/^\//,'') : '');
}
